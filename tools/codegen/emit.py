"""Render the schema model into ``esapp.grid`` and ``esapp.ts._catalog``, and sync to disk."""

from __future__ import annotations

import keyword
import re
from collections.abc import Iterable, Sequence
from dataclasses import dataclass
from pathlib import Path, PurePosixPath

from tools.codegen.model import FieldSpec, ObjectSpec
from tools.codegen.overrides import Overrides
from tools.codegen.subdata import Row as SubRow

MARKER = "# GENERATED by tools/codegen"
GRID = PurePosixPath("src/esapp/grid")
CATALOG = PurePosixPath("src/esapp/ts/_catalog.py")

_RESERVED = frozenset({"schema", "key"})  # GObject attributes a field must not shadow
_GROUP_RESERVED = frozenset({"of", "gtype", "fields"})  # catalog Group attributes
_VARIANT = re.compile(r"^(.*):(\d+)$")
_VARIANT_DOCS = 12  # indexed variants listed per docstring before summarizing the rest
_FLAG = "TSSave"  # TSSave* fields switch recording on and off: they get the YES/NO vocabulary
_FLAG_VOCAB = ("YES", "NO")
_SAVE_ALL = "TSSaveAll"


def render(
    objects: Sequence[ObjectSpec],
    overrides: Overrides,
    label: str,
    subdata: Iterable[SubRow] = (),
) -> dict[PurePosixPath, str]:
    """Every generated file, by repo-relative path."""
    header = f"{MARKER} from {label}. Do not edit.\n"
    vocab = dict(overrides.vocab)
    lists: dict[str, list[SubRow]] = {}
    for row in subdata:
        lists.setdefault(row.owner, []).append(row)
    if strays := set(lists) - {obj.name for obj in objects}:
        raise ValueError(f"SUBDATA of object types the schema lacks: {sorted(strays)}")
    files: dict[PurePosixPath, str] = {}
    modules: dict[str, str] = {}
    taken: set[str] = set()
    for obj in objects:
        cls = class_name(obj.name)
        if cls in modules:
            raise ValueError(f"object types {obj.name!r} and another both map to class {cls}")
        module = f"_{cls.lower()}"
        while module in taken:  # module files must differ on case-insensitive filesystems
            module += "_"
        taken.add(module)
        modules[cls] = module
        files[GRID / f"{module}.py"] = header + _module(obj, cls, vocab, lists.get(obj.name, []))
    files[GRID / "__init__.py"] = header + _PACKAGE.replace("@MODULES@", _entries(modules))
    files[GRID / "__init__.pyi"] = header + "".join(
        f"from .{module} import {cls} as {cls}\n" for cls, module in sorted(modules.items())
    )
    files[CATALOG] = header + _catalog(ts_catalog(objects, overrides))
    return files


def audit(objects: Iterable[ObjectSpec]) -> list[str]:
    """Key definitions whose positions are not exactly 1..n."""
    notes: list[str] = []
    for obj in objects:
        for kind, positions in (
            ("key", [f.key for f in obj.fields if f.key is not None]),
            ("alternate key", [f.alt_key for f in obj.fields if f.alt_key is not None]),
        ):
            if sorted(positions) != list(range(1, len(positions) + 1)):
                notes.append(f"{obj.name}: {kind} positions {sorted(positions)}")
    return notes


# ---------------------------------------------------------------------- names
def class_name(object_type: str) -> str:
    return _identifier(object_type.split(" ")[0])


def attr_name(field_base: str) -> str:
    name = _identifier(field_base)
    return f"{name}_" if name in _RESERVED else name


def _identifier(text: str) -> str:
    name = re.sub(r"\W", "_", text)
    if name[:1] == "3":
        name = f"Three{name[1:]}"  # 3WXFormer -> ThreeWXFormer
    elif name[:1].isdigit():
        name = f"_{name}"
    return f"{name}_" if keyword.iskeyword(name) else name


# ---------------------------------------------------------------------- object modules
def _module(
    obj: ObjectSpec, cls: str, vocab: dict[str, tuple[str, str]], subdata: Sequence[SubRow] = ()
) -> str:
    groups = _groups(obj.fields)
    keys = sorted((f for f in obj.fields if f.key is not None), key=lambda f: f.key or 0)
    alt = sorted((f for f in obj.fields if f.alt_key is not None), key=lambda f: f.alt_key or 0)

    options = [f"pw={_q(obj.name)}"]
    if keys:
        options.append(f"keys={_tuple(f.name for f in keys)}")
    if alt:
        options.append(f"alt_key={_tuple(f.name for f in alt)}")

    roles: set[str] = set()
    body: list[str] = []
    attrs: set[str] = set()
    for base, members in groups:
        attr = attr_name(base)
        while attr in attrs:
            attr += "_"
        attrs.add(attr)
        plain = members.get(0)
        variants = {n: f for n, f in members.items() if n}
        head = plain or variants[min(variants)]
        role = _role(plain) if plain else "V"
        args = [_q(base), head.dtype, role]
        if variants:
            entries = ", ".join(f"{n}: {_variant(f, head.dtype)}" for n, f in variants.items())
            args.append(f"{{{entries}}}")
        flag = _FLAG_VOCAB if base.startswith(_FLAG) else None
        if pair := vocab.get(f"{obj.name}.{base}", vocab.get(base, flag)):  # "Type.Field" first
            args.append(f"vocab=({_q(pair[0])}, {_q(pair[1])})")
        roles.update(re.findall(r"\b[KARMEVIN]\b", ", ".join(args[2:])))
        body.append(f"    {attr} = Field({', '.join(args)})")
        if doc := _docstring(cls, attr, plain, variants):
            body.append(doc)
    for sub in subdata:
        attr = attr_name(sub.name)
        while attr in attrs:  # a field of the same name keeps it
            attr += "_"
        attrs.add(attr)
        body.append(f"    {attr} = SubData({_q(sub.name)}, {_tuple(sub.columns)})")
        if sub.description:
            body.append(f'    """{_escape(sub.description)}"""')

    names = ["Field"] if groups else []
    names += ["GObject", *(["SubData"] if subdata else [])]
    imports = [f"from esapp.schema import {', '.join(names)}"]
    if roles:
        imports.append(f"from esapp.schema.roles import {', '.join(sorted(roles))}")
    lines = [
        *imports,
        "",
        "",
        f"class {cls}(GObject, {', '.join(options)}):",
        *(body or ["    ..."]),
    ]
    return "\n".join(lines) + "\n"


def _groups(fields: Sequence[FieldSpec]) -> list[tuple[str, dict[int, FieldSpec]]]:
    """Fields grouped by base name (``BusNum``, ``BusNum:1`` -> ``BusNum``), keys first."""
    grouped: dict[str, dict[int, FieldSpec]] = {}
    for f in fields:
        found = _VARIANT.match(f.name)
        base, n = (found[1], int(found[2])) if found else (f.name, 0)
        grouped.setdefault(base, {})[n] = f

    def rank(item: tuple[str, dict[int, FieldSpec]]) -> float:
        positions = [f.key for f in item[1].values() if f.key is not None]
        return min(positions) if positions else float("inf")

    return sorted(grouped.items(), key=rank)


def _role(f: FieldSpec) -> str:
    letters = [
        letter
        for letter, present in (
            ("K", f.key is not None),
            ("A", f.alt_key is not None),
            ("R", f.required),
            ("E", f.enterable),
            ("M", f.edit_only),
            ("I", f.identifier),
            ("N", f.nonscalar),
        )
        if present
    ]
    return " | ".join(letters) or "0"


def _variant(f: FieldSpec, base_dtype: str) -> str:
    return _role(f) if f.dtype == base_dtype else f"({_role(f)}, {f.dtype})"


def _docstring(cls: str, attr: str, plain: FieldSpec | None, variants: dict[int, FieldSpec]) -> str:
    base_text = plain.description if plain else ""
    lines = [base_text] if plain else [f"Indexed only: use ``{cls}.{attr}[n]``."]
    extra = [
        (n, f.description)
        for n, f in sorted(variants.items())
        if f.description not in ("", base_text)
    ]
    if extra:
        lines += [""] + [f"``[{n}]`` {text}" for n, text in extra[:_VARIANT_DOCS]]
        if len(extra) > _VARIANT_DOCS:
            lines.append(f"... and {len(extra) - _VARIANT_DOCS} more indexed variants.")
    lines = [_escape(line) for line in lines]
    while lines and not lines[0]:  # no base description: start at the variants
        lines.pop(0)
    if not lines:
        return ""
    if len(lines) == 1:
        return f'    """{lines[0]}"""'
    rest = "\n".join(f"    {line}" if line else "" for line in lines[1:])
    return f'    """{lines[0]}\n{rest}\n    """'


# ---------------------------------------------------------------------- package and catalog
_PACKAGE = '''"""Every PowerWorld object type, each loaded on first use.

``import esapp.grid`` is free; ``from esapp.grid import Bus`` loads only ``Bus``.
"""

from importlib import import_module

_MODULES: dict[str, str] = {
@MODULES@
}

__all__ = list(_MODULES)


def __getattr__(name: str) -> type:
    try:
        module = _MODULES[name]
    except KeyError:
        raise AttributeError(f"module {__name__!r} has no attribute {name!r}") from None
    cls = globals()[name] = getattr(import_module(f".{module}", __name__), name)
    return cls


def __dir__() -> list[str]:
    return __all__
'''


def _entries(modules: dict[str, str]) -> str:
    return "\n".join(f"    {_q(cls)}: {_q(module)}," for cls, module in sorted(modules.items()))


@dataclass(frozen=True, slots=True)
class Recordable:
    attr: str
    name: str  # base field name; indexed fields are addressed as TS.<group>.<attr>[n]
    flags: tuple[str, ...]  # any one of these TSSave fields records it
    doc: str


@dataclass(frozen=True, slots=True)
class Group:
    name: str
    cls: str  # esapp.grid class of the owner
    owner: str  # PowerWorld object type
    fields: tuple[Recordable, ...]


@dataclass(frozen=True, slots=True)
class Catalog:
    groups: tuple[Group, ...]
    recordable: tuple[str, ...]  # esapp.grid classes whose TSSave flags decide what is recorded
    unpaired: tuple[str, ...]  # numeric TS* fields of grouped types that no flag records


def ts_catalog(objects: Sequence[ObjectSpec], overrides: Overrides) -> Catalog:
    """Pair each group's fields with the TSSave flags that record them."""
    by_name = {obj.name: obj for obj in objects}
    save = dict(overrides.ts_save)
    if strays := [c for c in save if c.partition(".")[0] not in by_name]:
        raise ValueError(f"[ts.save] names unknown object types: {strays}")
    groups: list[Group] = []
    unpaired: list[str] = []
    for group, spec in overrides.ts_groups:
        if (obj := by_name.get(spec.owner)) is None:
            raise ValueError(f"[ts.groups] {group}: no object type {spec.owner!r}")
        members = dict(_groups(obj.fields))
        flags = sorted(  # a flag that cannot be set records nothing (Branch's XF flags)
            b
            for b, variants in members.items()
            if b.startswith(_FLAG) and b != _SAVE_ALL and 0 in variants and variants[0].enterable
        )
        for key, paired in save.items():
            owner, _, base = key.partition(".")
            if owner == spec.owner and (base not in members or set(paired) - set(flags)):
                raise ValueError(f"[ts.save] {key}: no such field or flag on {owner}")
        entries: list[Recordable] = []
        taken: set[str] = set()
        for base, variants in members.items():
            head = variants.get(0) or variants[min(variants)]
            paired = save.get(f"{spec.owner}.{base}")
            if paired is None:
                if not base.startswith("TS") or base.startswith(_FLAG) or head.dtype == "str":
                    continue
                paired = _pair(base, flags, overrides.ts_suffixes)
            if not paired:
                unpaired.append(f"{spec.owner}.{base}")
                continue
            short = base[len(spec.prefix) :] if base.startswith(spec.prefix) else base
            attr = attr_name(short.removeprefix("TS") or base)
            while attr in taken or attr in _GROUP_RESERVED:
                attr += "_"
            taken.add(attr)
            doc = head.description
            if 0 not in variants:
                doc = f"Indexed: ``TS.{group}.{attr}[n]``. {doc}".rstrip()
            entries.append(Recordable(attr, base, paired, doc))
        entries.sort(key=lambda c: c.attr)
        groups.append(Group(group, class_name(spec.owner), spec.owner, tuple(entries)))
    recordable = sorted(
        class_name(obj.name)
        for obj in objects
        if obj.name not in overrides.ts_unrecordable
        and any(f.name == _SAVE_ALL for f in obj.fields)
    )
    return Catalog(tuple(groups), tuple(recordable), tuple(unpaired))


def _pair(base: str, flags: Sequence[str], suffixes: Sequence[str]) -> tuple[str, ...]:
    """The flag named like ``base``, else one ``base`` extends by a known suffix."""
    name = base.removeprefix("TS").lower()
    stems = {flag.removeprefix(_FLAG).lower(): flag for flag in flags}
    if name in stems:
        return (stems[name],)
    for suffix in suffixes:
        stem = name.removesuffix(suffix.lower())
        if stem != name and stem in stems:
            return (stems[stem],)
    return ()


def _catalog(catalog: Catalog) -> str:
    lines = [
        '"""Recordable fields by object type: ``TS.Gen.Delta is Gen.TSGenDelta``."""',
        "",
        "from esapp.ts._recordable import Group, entry",
        "",
        f"RECORDABLE = {_tuple(catalog.recordable)}",
        '"""Object types whose TSSave flags decide what Simulator records."""',
        "",
        "",
        "class TS:",
        '    """Fields a transient simulation can record, one nested class per object type."""',
    ]
    for group in catalog.groups:
        lines += [
            "",
            f"    class {group.name}(Group, of={_q(group.cls)}):",
            f'        """Fields of {group.owner} objects."""',
            "",
        ]
        for c in group.fields:
            lines.append(f"        {c.attr} = entry({', '.join(map(_q, (c.name, *c.flags)))})")
            if c.doc:
                lines.append(f'        """{_escape(c.doc)}"""')
    return "\n".join(lines) + "\n"


# ---------------------------------------------------------------------- literals
def _q(text: str) -> str:
    return '"' + text.replace("\\", "\\\\").replace('"', '\\"') + '"'


def _tuple(names: Iterable[str]) -> str:
    items = [_q(n) for n in names]
    return f"({items[0]},)" if len(items) == 1 else f"({', '.join(items)})"  # () when empty


def _escape(text: str) -> str:
    return text.replace("\\", "\\\\").replace('"', '\\"')


# ---------------------------------------------------------------------- disk
@dataclass(frozen=True, slots=True)
class Sync:
    changed: list[PurePosixPath]  # differ from (or missing on) disk
    stale: list[PurePosixPath]  # generated modules no longer produced


def sync(files: dict[PurePosixPath, str], root: Path, *, check: bool) -> Sync:
    """Write only files whose text changed and remove stale generated modules.

    With ``check`` nothing is written; the result says what would change.
    """
    changed = [path for path, text in files.items() if _read(root / path) != text]
    stale = sorted(
        PurePosixPath(found.relative_to(root).as_posix())
        for found in (root / GRID).glob("_*.py")
        if PurePosixPath(found.relative_to(root).as_posix()) not in files and _generated(found)
    )
    if not check:
        for path in changed:
            target = root / path
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_text(files[path], encoding="utf-8", newline="\n")
        for path in stale:
            (root / path).unlink()
    return Sync(changed, stale)


def _read(path: Path) -> str | None:
    return path.read_text(encoding="utf-8") if path.is_file() else None


def _generated(path: Path) -> bool:
    with path.open(encoding="utf-8") as stream:
        return stream.readline().startswith(MARKER)
